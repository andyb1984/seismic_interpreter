class SegyImportDialog(QDialog):
    """Dialog to inspect and override SEG-Y vertical domain parameters on import"""
    def __init__(self, filename, auto_samples, auto_interval, auto_delay, parent=None):
        super().__init__(parent)
        self.setWindowTitle(f"Import SEG-Y Scale - {filename}")
        self.setMinimumWidth(380)

        layout = QVBoxLayout(self)
        form = QFormLayout()

        # Domain Selection
        self.combo_domain = QComboBox()
        self.combo_domain.addItems([
            "Two-Way Travel Time (ms)", 
            "Two-Way Travel Time (s)", 
            "Depth (m)", 
            "Depth (ft)"
        ])
        form.addRow("Vertical Domain:", self.combo_domain)

        # Start Time / Depth Offset (Sample 0)
        self.spin_start = QDoubleSpinBox()
        self.spin_start.setRange(-10000.0, 100000.0)
        self.spin_start.setDecimals(2)
        self.spin_start.setValue(float(auto_delay))
        form.addRow("Start (Sample 0 Offset):", self.spin_start)

        # Sample Interval
        self.spin_interval = QDoubleSpinBox()
        self.spin_interval.setRange(0.0001, 10000.0)
        self.spin_interval.setDecimals(4)
        self.spin_interval.setValue(float(auto_interval))
        form.addRow("Sample Interval (\u0394t / \u0394z):", self.spin_interval)

        # Sample Count (Read-only reference)
        self.lbl_samples = QLabel(str(auto_samples))
        form.addRow("Trace Samples:", self.lbl_samples)

        layout.addLayout(form)

        # OK / Cancel Buttons
        buttons = QDialogButtonBox(QDialogButtonBox.Ok | QDialogButtonBox.Cancel)
        buttons.accepted.connect(self.accept)
        buttons.rejected.connect(self.reject)
        layout.addWidget(buttons)

    def get_settings(self):
        return {
            'domain': self.combo_domain.currentText(),
            'start': self.spin_start.value(),
            'interval': self.spin_interval.value()
        }


class SeismicInterpreterDockWidget(QDockWidget):

    closingPlugin = pyqtSignal()

    def __init__(self, iface, parent=None):
        """Constructor."""
        super(SeismicInterpreterDockWidget, self).__init__(parent)
        self.iface = iface
        self.setWindowTitle("Seismic Interpreter")

        # Multi-line & picking state registry
        self.seismic_data = {}
        self.line_picks = {}  # Format: { line_name: [ {'pos': (trace_idx, y_val)}, ... ] }
        self.active_line = None
        self.marker = None
        self.map_layer = None
        self.horizon_layer = None
        
        self.is_picking = False
        self.current_horizon_name = "Horizon_A"

        # Main Widget & Layout
        self.main_widget = QWidget()
        self.layout = QVBoxLayout(self.main_widget)
        self.layout.setContentsMargins(5, 5, 5, 5)

        # Top Control Bar
        self.top_bar = QHBoxLayout()
        
        self.btn_load = QPushButton("Open SEG-Y File(s)")
        self.btn_load.clicked.connect(self.select_segy_files)
        self.top_bar.addWidget(self.btn_load)

        # Line Selection Dropdown
        self.combo_lines = QComboBox()
        self.combo_lines.currentIndexChanged.connect(self.on_line_dropdown_changed)
        self.top_bar.addWidget(self.combo_lines)

        # Horizon Picking Toggle Button
        self.btn_pick_mode = QPushButton("Pick Horizon: OFF")
        self.btn_pick_mode.setCheckable(True)
        self.btn_pick_mode.toggled.connect(self.toggle_picking_mode)
        self.top_bar.addWidget(self.btn_pick_mode)

        self.lbl_info = QLabel("No lines loaded")
        self.lbl_info.setStyleSheet("color: #888; font-size: 11px;")
        self.top_bar.addWidget(self.lbl_info)

        self.layout.addLayout(self.top_bar)

        # PyQtGraph Viewport Setup
        self.plot_widget = pg.PlotWidget()
        self.plot_widget.setBackground('k')
        self.img_item = pg.ImageItem()
        self.plot_widget.addItem(self.img_item)
        
        self.plot_widget.getViewBox().invertY(True)
        self.plot_widget.setLabel('left', 'Vertical Axis')
        self.plot_widget.setLabel('bottom', 'Trace Index')

        # Red-White-Blue Seismic Colormap
        pos = np.array([0.0, 0.5, 1.0])
        color = np.array([[0, 0, 255, 255], [255, 255, 255, 255], [255, 0, 0, 255]], dtype=np.uint8)
        cmap = pg.ColorMap(pos, color)
        self.img_item.setLookupTable(cmap.getLookupTable())

        # Scatter plot item on pyqtgraph canvas for displaying picks on section
        self.horizon_scatter = pg.ScatterPlotItem(size=8, pen=pg.mkPen(None), brush=pg.mkBrush(255, 255, 0, 200))
        self.plot_widget.addItem(self.horizon_scatter)

        self.layout.addWidget(self.plot_widget)
        self.setWidget(self.main_widget)

        # Event Connections & Map Layers Initialization
        self.plot_widget.scene().sigMouseClicked.connect(self.on_seismic_clicked)
        self.init_map_layer()
        self.init_horizon_layer()

    def get_project_crs_authid(self):
        """Returns active QGIS map canvas CRS authid (e.g., EPSG:27700 or EPSG:4326)"""
        crs = self.iface.mapCanvas().mapSettings().destinationCrs()
        return crs.authid() if crs.isValid() else "EPSG:27700"

    def init_map_layer(self):
        """Initializes a master memory layer for all loaded seismic navigation tracks"""
        if self.map_layer is None:
            crs_str = self.get_project_crs_authid()
            self.map_layer = QgsVectorLayer(f"LineString?crs={crs_str}", "Seismic Lines", "memory")
            provider = self.map_layer.dataProvider()
            provider.addAttributes([QgsField("LineName", QVariant.String)])
            self.map_layer.updateFields()

            symbol = QgsLineSymbol.createSimple({'color': 'red', 'width': '0.6'})
            self.map_layer.setRenderer(QgsSingleSymbolRenderer(symbol))

            QgsProject.instance().addMapLayer(self.map_layer)
            self.map_layer.selectionChanged.connect(self.on_map_selection_changed)

    def init_horizon_layer(self):
        """Initializes a 3D Point memory layer for horizon interpretation picks"""
        if self.horizon_layer is None:
            crs_str = self.get_project_crs_authid()
            self.horizon_layer = QgsVectorLayer(f"PointZ?crs={crs_str}", "Horizon Picks", "memory")
            provider = self.horizon_layer.dataProvider()
            provider.addAttributes([
                QgsField("HorizonName", QVariant.String),
                QgsField("LineName", QVariant.String),
                QgsField("TraceIdx", QVariant.Int),
                QgsField("Value", QVariant.Double)
            ])
            self.horizon_layer.updateFields()

            symbol = QgsMarkerSymbol.createSimple({'color': 'yellow', 'size': '3'})
            self.horizon_layer.setRenderer(QgsSingleSymbolRenderer(symbol))

            QgsProject.instance().addMapLayer(self.horizon_layer)

    def select_segy_files(self):
        """Allows multi-file selection from dialog"""
        filepaths, _ = QFileDialog.getOpenFileNames(
            self, "Select SEG-Y File(s)", "", "SEG-Y Files (*.sgy *.segy)"
        )
        for filepath in filepaths:
            self.load_segy_file(filepath)

    def load_segy_file(self, filepath):
        """Inspects SEG-Y vertical parameters, extracts coordinates, and registers file"""
        line_name = os.path.splitext(os.path.basename(filepath))[0]
        if line_name in self.seismic_data:
            return

        with segyio.open(filepath, ignore_geometry=True) as f:
            x_raw = f.attributes(segyio.TraceField.SourceX)[:]
            y_raw = f.attributes(segyio.TraceField.SourceY)[:]
            scalars = f.attributes(segyio.TraceField.SourceGroupScalar)[:]

            points = []
            for x, y, s in zip(x_raw, y_raw, scalars):
                factor = 1.0 / abs(s) if s < 0 else (float(s) if s > 0 else 1.0)
                points.append(QgsPointXY(x * factor, y * factor))

            dt_us = f.bin[segyio.BinField.Interval]
            num_samples = f.bin[segyio.BinField.Samples]
            start_delay = f.header[0][segyio.TraceField.DelayRecordingTime]
            
            auto_interval = dt_us / 1000.0 if dt_us > 0 else 4.0

        dlg = SegyImportDialog(line_name, num_samples, auto_interval, start_delay, self)
        if dlg.exec_() != QDialog.Accepted:
            return

        settings = dlg.get_settings()

        feat = QgsFeature(self.map_layer.fields())
        feat.setGeometry(QgsGeometry.fromPolylineXY(points))
        feat.setAttribute("LineName", line_name)
        
        provider = self.map_layer.dataProvider()
        (success, added_features) = provider.addFeatures([feat])
        
        self.map_layer.updateExtents()
        self.map_layer.triggerRepaint()

        feat_id = added_features[0].id() if added_features else None

        self.seismic_data[line_name] = {
            'path': filepath,
            'points': points,
            'feature_id': feat_id,
            'domain': settings['domain'],
            'start': settings['start'],
            'interval': settings['interval'],
            'num_samples': num_samples
        }

        self.combo_lines.blockSignals(True)
        self.combo_lines.addItem(line_name)
        self.combo_lines.blockSignals(False)

        if len(self.seismic_data) == 1:
            self.display_line(line_name)
            self.iface.mapCanvas().setExtent(self.map_layer.extent())
            self.iface.mapCanvas().refresh()

    def display_line(self, line_name):
        """Loads section amplitudes and scales viewport to real time/depth coordinates"""
        if line_name not in self.seismic_data:
            return

        self.active_line = line_name
        meta = self.seismic_data[line_name]
        filepath = meta['path']
        
        start_y = meta['start']
        interval_y = meta['interval']
        domain_str = meta['domain']

        with segyio.open(filepath, ignore_geometry=True) as f:
            data = segyio.tools.collect(f.trace[:])
            num_traces, num_samples = data.shape
            
            total_y_range = num_samples * interval_y
            
            self.img_item.setImage(data)
            self.img_item.setRect(QRectF(0, start_y, num_traces, total_y_range))

        self.plot_widget.setLabel('left', domain_str)
        self.lbl_info.setText(f"Active: {line_name}")
        
        # Clear section scatter plot and reload picks for this line only
        self.horizon_scatter.clear()
        if line_name in self.line_picks:
            self.horizon_scatter.addPoints(self.line_picks[line_name])

        # Sync Dropdown Index
        idx = self.combo_lines.findText(line_name)
        if idx >= 0 and self.combo_lines.currentIndex() != idx:
            self.combo_lines.blockSignals(True)
            self.combo_lines.setCurrentIndex(idx)
            self.combo_lines.blockSignals(False)

    def toggle_picking_mode(self, checked):
        """Toggles horizon picking mode state"""
        self.is_picking = checked
        self.btn_pick_mode.setText("Pick Horizon: ON" if checked else "Pick Horizon: OFF")
        self.btn_pick_mode.setStyleSheet("background-color: #4CAF50; color: white;" if checked else "")

    def on_line_dropdown_changed(self, index):
        """Dropdown selector handler"""
        line_name = self.combo_lines.itemText(index)
        if line_name:
            self.display_line(line_name)

    def on_map_selection_changed(self, selected_ids, deselected_ids, clear_and_select):
        """Map feature selection listener - queries LineName directly from selected feature"""
        if not selected_ids:
            return

        selected_id = selected_ids[0]
        feature = self.map_layer.getFeature(selected_id)
        
        if feature.isValid():
            line_name = feature.attribute("LineName")
            if line_name in self.seismic_data and line_name != self.active_line:
                self.display_line(line_name)

    def on_seismic_clicked(self, event):
        """Handles mouse clicks on seismic section for navigation or horizon digitizing"""
        if event.isAccepted() or not self.active_line:
            return

        pos = event.scenePos()
        mouse_point = self.plot_widget.plotItem.vb.mapSceneToView(pos)
        trace_idx = int(round(mouse_point.x()))
        val_y = mouse_point.y()

        points = self.seismic_data[self.active_line]['points']

        if 0 <= trace_idx < len(points):
            if self.is_picking:
                pick_data = {'pos': (trace_idx, val_y)}
                
                # Register pick in line history
                if self.active_line not in self.line_picks:
                    self.line_picks[self.active_line] = []
                self.line_picks[self.active_line].append(pick_data)

                # 1. Add pick to pyqtgraph canvas
                self.horizon_scatter.addPoints([pick_data])
                
                # 2. Map trace index to real-world map coordinates (Easting, Northing)
                map_pt = points[trace_idx]
                
                # 3. Save 3D Point to QGIS Map Layer (Z = Calibrated Time/Depth value)
                feat = QgsFeature(self.horizon_layer.fields())
                feat.setGeometry(QgsGeometry.fromPoint(QgsPoint(map_pt.x(), map_pt.y(), val_y)))
                feat.setAttributes([self.current_horizon_name, self.active_line, trace_idx, val_y])
                
                provider = self.horizon_layer.dataProvider()
                provider.addFeatures([feat])
                
                # Force QGIS to re-evaluate the horizon layer extents and trigger a fresh render
                self.horizon_layer.updateExtents()
                self.horizon_layer.triggerRepaint()
                self.iface.mapCanvas().refresh()
            else:
                # Standard navigation marker
                self.highlight_map_location(points[trace_idx])

    def highlight_map_location(self, point):
        """Places red marker on map canvas"""
        if self.marker is None:
            self.marker = QgsRubberBand(self.iface.mapCanvas(), QgsWkbTypes.PointGeometry)
            self.marker.setColor(QColor(255, 0, 0))
            self.marker.setIconSize(12)

        self.marker.setToGeometry(QgsGeometry.fromPointXY(point), None)

    def closeEvent(self, event):
        """Cleanup on panel close"""
        if self.marker:
            self.iface.mapCanvas().scene().removeItem(self.marker)
        self.closingPlugin.emit()
        event.accept()